"""Сокращение длинных названий пассивных способностей (узкий список выбора) -> edits/84d_names.json."""
import json, glob, re, sys
sys.stdout.reconfigure(encoding='utf-8')
from PIL import ImageFont
F = ImageFont.truetype('fonts/BO-UDShinGoNTPr6N-Reg.otf', 32); LIM = 606
ru = json.load(open('ru/ru.json', encoding='utf-8'))
for f in sorted(glob.glob('edits/*.json')):
    if f.replace(chr(92), '/') < 'edits/84d': ru.update(json.load(open(f, encoding='utf-8')))
N = lambda s: s.replace(' ', ' ')
RULES = [
 (r'^Восстановление (О[МЗ]) при критическом ударе$', r'\1 за критический удар'),
 (r'^Восстановление (О[МЗ]) за победу над врагом$', r'\1 за победу над врагом'),
 (r'^Восстановление (О[МЗ]) при пробитии$', r'\1 за пробитие'),
 (r'^Восстановление (О[МЗ]) при обычной атаке$', r'\1 за обычную атаку'),
 (r'^Восстановление (О[МЗ]) при получении урона$', r'\1 при получении урона'),
 (r'^Восстановление (О[МЗ]) при ходьбе$', r'\1 при ходьбе'),
 (r'^Заряд предела при критическом ударе$', 'Заряд предела за крит. удар'),
 (r'^Заряд предела за победу над врагом$', 'Заряд предела за победу'),
 (r'^Заряд предела при получении урона$', 'Заряд предела от урона'),
 (r'^Заряд предела при обычной атаке$', 'Заряд предела за атаку'),
 (r'^Заряд предела при пробитии$', 'Заряд предела за пробитие'),
 (r'^Заряд предела при лечении$', 'Заряд предела за лечение'),
 (r'^Урон пробития слабой стихией (\+\d+%)$', r'Пробитие по слабости \1'),
 (r'^(Пробитие|Атака) ценой здоровья: (.+)$', r'\1 ценой ОЗ: \2'),
 (r'^Автовосстановление (О[МЗ]): (.+)$', r'Автовосполнение \1: \2'),
 (r'^Невосприимчивость к физическим атакам$', 'Иммунитет к физ. атакам'),
 (r'^Невосприимчивость к магии$', 'Иммунитет к магии'),
 (r'^Физическая контратака выбранным приёмом$', 'Физ. контратака приёмом'),
 (r'^Контратака заданной способностью$', 'Маг. контратака приёмом'),
]
out = {}; ren = {}
for k, v in ru.items():
    if k.split('␟')[0] not in ('ST_PassiveSkillName',): continue
    t = N(v)
    for a, b in RULES:
        n = re.sub(a, b, t)
        if n != t: out[k] = n; ren[t] = n; break
json.dump(out, open('edits/84d_names.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
print('изменено ключей:', len(out))
for a, b in sorted(ren.items()): print(f'  {F.getlength(b)/LIM:.0%}  {a}  →  {b}')
# где ещё упоминаются старые названия
refs = [(k, t) for k, v in ru.items() for t in ren if k.split('␟')[0] != 'ST_PassiveSkillName' and t in N(v)]
print('упоминания в других текстах:', [(k.split('␟')[1], t) for k, t in refs][:20])
